// Builds the "chat with my work" corpus from the site's own pages.
// Pulls the visible text (JSX text and prose string literals) out of each
// case study, the about and resume pages and data.ts, in source order, and
// writes src/lib/chat/corpus.generated.ts. Runs before every build.
import fs from 'node:fs'
import path from 'node:path'
import ts from 'typescript'

const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..')
const OUT = path.join(ROOT, 'src/lib/chat/corpus.generated.ts')

// Attribute and property names whose values are never prose.
const SKIP_KEYS = new Set([
  'className', 'style', 'href', 'src', 'id', 'key', 'lang', 'type', 'rel', 'target',
  'fontFamily', 'color', 'background', 'border', 'padding', 'margin', 'gridTemplateColumns',
  'canonical', 'url', 'images', 'card', 'width', 'height', 'slug', 'icon', 'accent', 'tone',
  'fontSize', 'fontWeight', 'letterSpacing', 'lineHeight', 'display', 'transition', 'transform',
  'boxShadow', 'borderRadius', 'gap', 'maxWidth', 'position', 'image', 'img', 'shot', 'poster',
])

function looksLikeCode(s)
{
  if (/var\(--|^#[0-9a-f]{3,8}$|rgba?\(|\d+px|^\/[\w/.-]*$|^https?:\/\/\S+$|^[\w-]+\.(webp|png|jpg|svg|pdf)$/i.test(s)) {
    return true
  }
  if (/monospace|sans-serif|cubic-bezier/.test(s)) {
    return true
  }
  // Metric values ('353', '37K+', '<1s') are worth keeping.
  if (/\d/.test(s) && s.length <= 12) {
    return false
  }
  // Single tokens like 'flex', 'center', 'mono' carry no meaning on their own.
  return !/\s/.test(s) && s.length < 4
}

function keyOf(node)
{
  const p = node.parent
  if (!p) {
    return null
  }
  if (ts.isJsxAttribute(p)) {
    return p.name.getText()
  }
  if (ts.isJsxExpression(p) && p.parent && ts.isJsxAttribute(p.parent)) {
    return p.parent.name.getText()
  }
  if (ts.isPropertyAssignment(p) && p.initializer === node) {
    return p.name.getText().replace(/['"]/g, '')
  }
  return null
}

function insideSkipped(node)
{
  for (let n = node; n; n = n.parent) {
    const k = keyOf(n)
    if (k && SKIP_KEYS.has(k)) {
      return true
    }
    if (ts.isImportDeclaration(n) || ts.isExportDeclaration(n)) {
      return true
    }
    // Font and style constants: const MONO = '...'
    if (ts.isVariableDeclaration(n) && /^(MONO|SANS|DISPLAY|SERIF|GREEN|ACCENT|PROSE|[A-Z_]*STYLE[A-Z_]*)$/.test(n.name.getText())) {
      return true
    }
  }
  return false
}

function extract(file)
{
  const text = fs.readFileSync(file, 'utf8')
  const src = ts.createSourceFile(file, text, ts.ScriptTarget.Latest, true, ts.ScriptKind.TSX)
  const out = []
  const visit = (node) => {
    let s = null
    if (ts.isJsxText(node)) {
      s = node.getText()
    } else if (ts.isStringLiteral(node) || ts.isNoSubstitutionTemplateLiteral(node)) {
      if (!insideSkipped(node)) {
        s = node.text
      }
    } else if (ts.isTemplateExpression(node) && !insideSkipped(node)) {
      s = node.getText().slice(1, -1).replace(/\$\{[^}]*\}/g, ' ')
    }
    if (s !== null) {
      s = s.replace(/\s+/g, ' ').trim()
      if (s && !looksLikeCode(s)) {
        out.push(s)
      }
      if (ts.isTemplateExpression(node)) {
        return
      }
    }
    ts.forEachChild(node, visit)
  }
  visit(src)
  // Drop exact repeats (metadata repeats the description three times).
  const seen = new Set()
  return out.filter((s) => {
    if (seen.has(s)) {
      return false
    }
    seen.add(s)
    return true
  })
}

function joinLines(parts)
{
  // Short fragments (labels, chips) go on one line; prose gets its own line.
  const lines = []
  let row = []
  for (const p of parts) {
    if (p.length < 40) {
      row.push(p)
      continue
    }
    if (row.length) {
      lines.push(row.join(' · '))
      row = []
    }
    lines.push(p)
  }
  if (row.length) {
    lines.push(row.join(' · '))
  }
  return lines.join('\n')
}

const sections = []
const add = (title, file) => {
  sections.push(`<page path="${title}">\n${joinLines(extract(path.join(ROOT, file)))}\n</page>`)
}

add('data: project list and archive', 'src/lib/data.ts')
add('/about', 'src/app/about/page.tsx')
add('/resume', 'src/app/resume/page.tsx')
const dir = path.join(ROOT, 'src/app/projects')
for (const slug of fs.readdirSync(dir).sort()) {
  const page = path.join(dir, slug, 'page.tsx')
  if (!slug.startsWith('_') && fs.existsSync(page)) {
    add(`/projects/${slug}`, path.relative(ROOT, page))
  }
}

const corpus = sections.join('\n\n')
const body = `// Generated by scripts/build-chat-corpus.mjs. Do not edit by hand.\n` +
  `export const CORPUS = ${JSON.stringify(corpus)}\n`
const prev = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : ''
if (prev !== body) {
  fs.writeFileSync(OUT, body)
}
console.log(`chat corpus: ${sections.length} pages, ${corpus.length} chars (~${Math.round(corpus.length / 4)} tokens)`)
